    private void btnprosesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnprosesActionPerformed
try {
    // 1. Mengambil data dari inputan GUI Anda
    String kodeKursus = txtnama.getText();
    String namaKursus = cmb.getSelectedItem().toString();
    
    // 2. Mengubah teks angka menjadi tipe data Double
    double biaya = Double.parseDouble(txtjumlah1.getText());
    double diskon = Double.parseDouble(txtjumlah2.getText());   
    
    // 3. Menghitung nominal diskon dan total biaya
    double nominalDiskon = biaya * (diskon / 100);
    double totalBiaya = biaya - nominalDiskon;
   
    // 4. Menyusun format teks untuk output
    String hasil = "HASIL PENDAFTARAN KURSUS\n"
                 + "============================\n"
                 + "Kode Kursus  : " + kodeKursus + "\n"
                 + "Nama Kursus  : " + namaKursus + "\n"
                 + "Level: INTERMEDIATE\n"
                 + "Biaya Kursus : Rp " + biaya + "\n"
                 + "Diskon (%)   : " + diskon + "%\n"
                 + "Biaya akhir  : Rp " + totalBiaya;
  
    // 5. Menampilkan pop-up hasil cetak pendaftaran
    javax.swing.JOptionPane.showMessageDialog(this, hasil, "Hasil Pendaftaran Kursus", javax.swing.JOptionPane.INFORMATION_MESSAGE);

} catch (NumberFormatException e) {
    // Menampilkan peringatan jika kolom Biaya atau Diskon diisi selain angka / kosong
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Biaya dan Diskon harus diisi dengan angka dan tidak boleh kosong!",
        "Input Tidak Valid",
        javax.swing.JOptionPane.ERROR_MESSAGE
    );
} catch (NullPointerException e) {
    // Mengantisipasi jika ComboBox (cmb) belum dipilih atau kosong
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Silahkan pilih Nama Kursus terlebih dahulu!",
        "Pilihan Kosong",
        javax.swing.JOptionPane.WARNING_MESSAGE
    );
    }//GEN-LAST:event_btnprosesActionPerformed
    }  
